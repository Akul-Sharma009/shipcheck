"""Plain-data views of a Report: status counts, fix list, Markdown export."""
from datetime import datetime, timezone
from typing import Dict, List, Optional, Tuple

try:
    from zoneinfo import ZoneInfo
except ImportError:  # pragma: no cover
    ZoneInfo = None  # type: ignore

from shipcheck.schemas import Report

LABEL = {"pass": "PASS", "fail": "FAIL", "unclear": "UNCLEAR", "not_checkable": "CONFIRM"}


def keyword_missed(report: Report) -> List[str]:
    """Requirement ids ShipCheck failed that a keyword/file check would have passed."""
    return [v.requirement_id for v in report.verdicts
            if v.status == "fail" and report.keyword.get(v.requirement_id) == "pass"]


def counts(report: Report) -> Dict[str, int]:
    out = {s: 0 for s in LABEL}
    for v in report.verdicts:
        out[v.status] += 1
    return out


def to_fix(report: Report) -> List[Tuple[str, str, str, str]]:
    """(status, label, problem, fix) for every failing/unclear check and requirement, failures first."""
    reqs = {r.id: r.text for r in report.rules.requirements}
    # A check that already decided a requirement (its id leads that verdict's evidence) is listed once, there.
    covered = {e.split(":", 1)[0] for v in report.verdicts if v.status in ("fail", "unclear") for e in v.evidence}
    items = [(c.status, c.id, c.name, c.fix or "") for c in report.checks
             if c.status in ("fail", "unclear") and c.required and c.id not in covered]
    items += [(v.status, v.requirement_id, reqs.get(v.requirement_id, ""), v.fix or "")
              for v in report.verdicts if v.status in ("fail", "unclear")]
    return sorted(items, key=lambda x: x[0] != "fail")


def to_markdown(report: Report) -> str:
    f, r = report.facts, report.rules
    reqs = {q.id: q.text for q in r.requirements}
    c = counts(report)
    lines = [f"# ShipCheck report: {f.full_name}", "",
             f"Hackathon: {r.hackathon_name} ({report.hackathon_url})  ",
             f"Commit: {f.head_sha[:7]} · checked {report.created_at[:16].replace('T', ' ')} UTC", "",
             f"**{c['pass']} pass · {c['fail']} fail · {c['unclear']} unclear · {c['not_checkable']} to confirm yourself**",
             "", "## Fix before you submit"]
    lines += [f"- **{LABEL[s]} {i}** {p}  \n  Fix: {fx}" for s, i, p, fx in to_fix(report)] or ["- Nothing to fix."]
    lines += ["", "## Repo checks (GitHub API, no AI)"]
    lines += [f"- {LABEL[x.status]} {x.id} {x.name}: {'; '.join(x.evidence)}" for x in report.checks]
    lines += ["", "## Requirements"]
    for v in report.verdicts:
        lines.append(f"- {LABEL[v.status]} {v.requirement_id}: {reqs.get(v.requirement_id, '')}")
        if v.evidence and v.status != "not_checkable":
            lines.append(f"  - Evidence: {'; '.join(v.evidence)}")
        if v.fix:
            lines.append(f"  - Fix: {v.fix}")
    lines += ["", "Generated by ShipCheck (NVIDIA Nemotron on Nebius Token Factory)."]
    return "\n".join(lines)


def changes(prev: Report, cur: Report) -> Tuple[List[str], List[str]]:
    """(fixed, newly broken) between two checks of the same repo, as 'ID name' labels."""
    def statuses(r: Report) -> Dict[str, Tuple[str, str]]:
        names = {q.id: q.text for q in r.rules.requirements}
        out = {c.id: (c.status, c.name) for c in r.checks if c.required}
        out.update({v.requirement_id: (v.status, names.get(v.requirement_id, "")) for v in r.verdicts})
        return out

    before, after = statuses(prev), statuses(cur)
    bad = ("fail", "unclear")
    fixed = [f"{i} {after[i][1][:70]}" for i in after if i in before and before[i][0] in bad and after[i][0] == "pass"]
    broke = [f"{i} {after[i][1][:70]}" for i in after if i in before and before[i][0] == "pass" and after[i][0] in bad]
    return fixed, broke


def countdown(deadline_iso: Optional[str], tz_name: Optional[str] = None) -> Optional[str]:
    """'Deadline in 4h 39m · Sat 31 Oct, 01:00 (Asia/Singapore)', in the viewer's timezone when known."""
    if not deadline_iso:
        return None
    try:
        end = datetime.fromisoformat(deadline_iso.strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    if not end.tzinfo:
        return None
    try:
        tz = ZoneInfo(tz_name) if tz_name else timezone.utc
    except Exception:
        tz = timezone.utc
    local = end.astimezone(tz).strftime("%a %d %b, %H:%M") + f" ({tz_name or 'UTC'})"
    secs = int((end - datetime.now(timezone.utc)).total_seconds())
    if secs <= 0:
        return f"Submissions closed {_span(-secs)} ago · {local}"
    return f"Deadline in {_span(secs)} · {local}"


def _span(secs: int) -> str:
    d, rem = divmod(secs, 86400)
    h, m = rem // 3600, rem % 3600 // 60
    return f"{d}d {h}h" if d else f"{h}h {m:02d}m"
